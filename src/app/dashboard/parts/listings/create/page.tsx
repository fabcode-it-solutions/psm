import CreateListing from "@/app/dashboard/partListing/CreateListing";
import { Metadata } from "next";
import React from "react";

export const metadata: Metadata = {
  title: "Create Listing - Dashboard",
  description: "Generated by create next app",
};

export default async function Page({
  searchParams,
}: {
  searchParams: Promise<{ [key: string]: string | string[] | undefined }>;
}) {
  const partId = (await searchParams).template;

  const [partData] = await Promise.all([
    fetch(`${process.env.NEXT_PUBLIC_API_PATH}/parts/${partId}`, {
      next: {
        revalidate: 1800,
        tags: ["popular-users"],
      },
    }).catch((error) => {
      console.error("Failed to fetch popular users:", error);
      return { json: () => ({ data: [] }) };
    }),
  ]);
  const templateData = await partData.json();

  return <CreateListing partData={templateData.data} />;
}
